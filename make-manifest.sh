#!/usr/bin/env bash
# Regenerates repos.tsv and not-in-git.txt from a populated checkout.
# Run on the host (or in the VM once it is populated) from anywhere:
#
#   ./make-manifest.sh [projects-root]      # default ~/projects/current
#
# Why a manifest instead of `gh repo list`: seven of these directories are
# named differently from their GitHub repo (exercise -> strength-guide,
# youtube-aggregator -> video-aggregator, toolbox -> tool-box, ...). Cloning
# by repo name would produce wrongly-named directories and break every
# documented path. The manifest records the mapping that actually exists.
set -euo pipefail

ROOT="${1:-$HOME/projects/current}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
[ -d "$ROOT" ] || { echo "no such directory: $ROOT" >&2; exit 1; }

# BSD sed has no non-greedy quantifier, so strip the .git suffix with shell
# expansion and pull owner/repo out with plain ERE.
repo_of() {
  local u
  u="$(git -C "$1" remote get-url origin 2>/dev/null)" || return 0
  [ -n "$u" ] || return 0
  u="${u%.git}"
  printf '%s/%s\n' \
    "$(printf '%s' "$u" | sed -E 's#.*[:/]([^/]+)/[^/]+$#\1#')" \
    "${u##*/}"
}
branch_of() { git -C "$1" branch --show-current 2>/dev/null; }

{
  echo "# Generated by make-manifest.sh — do not hand-edit; regenerate instead."
  echo "# path<TAB>owner/repo<TAB>branch"
  echo "#"
  echo "# Submodules are deliberately absent: clone-all.sh passes"
  echo "# --recurse-submodules, so pauls-blog/themes/hugo-simple-beauty and"
  echo "# strength/{strength-guide,strength-programs} arrive with their parent."
  echo ""

  # --- top level ---
  for d in "$ROOT"/*/; do
    d="${d%/}"; name="$(basename "$d")"
    [ -d "$d/.git" ] || continue          # skips worktrees (.git is a file)
    r="$(repo_of "$d")"; [ -n "$r" ] || continue
    printf '%s\t%s\t%s\n' "$name" "$r" "$(branch_of "$d")"
  done

  echo ""
  echo "# --- nested, independent clones (NOT submodules) ---"
  # Parent dirs that are plain folders holding their own clones.
  for d in "$ROOT"/*/*/ ; do
    d="${d%/}"
    [ -d "$d/.git" ] || continue
    rel="${d#$ROOT/}"
    parent="$ROOT/${rel%%/*}"
    child="${rel#*/}"
    # a submodule is listed in the parent's .gitmodules — skip those
    if [ -f "$parent/.gitmodules" ] && grep -q "path = $child\$" "$parent/.gitmodules" 2>/dev/null; then
      continue
    fi
    r="$(repo_of "$d")"; [ -n "$r" ] || continue
    printf '%s\t%s\t%s\n' "$rel" "$r" "$(branch_of "$d")"
  done
} > "$HERE/repos.tsv"

# --- worktrees: recreated with `git worktree add`, not clone ---
{
  echo "# Generated by make-manifest.sh. Worktrees of another repo in this list."
  echo "# path<TAB>parent-path<TAB>branch"
  echo ""
  for d in "$ROOT"/*/; do
    d="${d%/}"; name="$(basename "$d")"
    [ -f "$d/.git" ] || continue
    gitdir="$(sed -E 's/^gitdir: //' "$d/.git")"
    # gitdir is <parent>/.git/worktrees/<name>, so the parent repo is three
    # levels up — not two.
    parent="$(basename "$(dirname "$(dirname "$(dirname "$gitdir")")")")"
    printf '%s\t%s\t%s\n' "$name" "$parent" "$(branch_of "$d")"
  done
} > "$HERE/worktrees.tsv"

# --- directories git does not cover at all ---
{
  echo "# Generated by make-manifest.sh."
  echo "#"
  echo "# These directories are NOT in git, anywhere. A clone-based migration"
  echo "# loses them. Copy them across deliberately, or decide to drop them:"
  echo "#   limactl copy -r ~/projects/current/<name> dev:/home/\$USER/projects/current/"
  echo ""
  for d in "$ROOT"/*/; do
    d="${d%/}"; name="$(basename "$d")"
    [ -e "$d/.git" ] && continue
    if find "$d" -maxdepth 3 -name .git -print -quit 2>/dev/null | grep -q .; then continue; fi
    printf '%-28s %s\n' "$name" "$(du -sh "$d" 2>/dev/null | cut -f1)"
  done
} > "$HERE/not-in-git.txt"

echo "wrote:"
printf '  repos.tsv      %s repos\n'     "$(grep -cvE '^\s*(#|$)' "$HERE/repos.tsv")"
printf '  worktrees.tsv  %s worktrees\n' "$(grep -cvE '^\s*(#|$)' "$HERE/worktrees.tsv")"
printf '  not-in-git.txt %s dirs\n'      "$(grep -cvE '^\s*(#|$)' "$HERE/not-in-git.txt")"
